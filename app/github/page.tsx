'use client';

import { useCallback, useEffect, useRef, useState } from 'react';
import Image from 'next/image';
import { VscRepo, VscPerson, VscStarEmpty, VscRepoForked, VscLinkExternal, VscGithub } from 'react-icons/vsc';

import RepoCard from '@/components/RepoCard';
import { Repo, User } from '@/types';

import styles from '@/styles/GithubPage.module.css';

const GITHUB_USERNAME = 'pyatrick666';
const REFRESH_INTERVAL = 10 * 60 * 1000;

export default function GithubPage() {
  const [user, setUser] = useState<User | null>(null);
  const [repos, setRepos] = useState<Repo[]>([]);
  const [calendar, setCalendar] = useState<{ totalContributions: number; weeks: { contributionDays: { date: string; contributionCount: number; contributionLevel: string }[] }[] } | null>(null);
  const [loading, setLoading] = useState(true);
  const [lastUpdated, setLastUpdated] = useState<Date | null>(null);
  const [error, setError] = useState<string | null>(null);
  const lastRequestAt = useRef(0);

  const refreshGithubData = useCallback(async (isInitial = false) => {
    const now = Date.now();

    // Avoid duplicate requests from rapid tab switches or timer/visibility overlap.
    if (!isInitial && now - lastRequestAt.current < REFRESH_INTERVAL) return;
    lastRequestAt.current = now;
    if (isInitial) setLoading(true);

    try {
      // GitHub Pages serves a data snapshot generated by Actions, avoiding
      // anonymous browser API rate limits and cross-origin API failures.
      const basePath = window.location.pathname.startsWith('/Professional-Portfolio')
        ? '/Professional-Portfolio'
        : '';
      const response = await fetch(
        `${basePath}/github-data.json?v=${Math.floor(now / REFRESH_INTERVAL)}`,
        {
          cache: 'no-store',
          headers: { Accept: 'application/json' },
        },
      );

      if (!response.ok) {
        throw new Error('GitHub profile data could not be loaded. Please refresh shortly.');
      }

      const data: { user?: User; repos?: Repo[]; calendar?: typeof calendar } = await response.json();
      if (!data.user || !Array.isArray(data.repos) || !data.calendar?.weeks?.length) {
        throw new Error('GitHub profile data is incomplete. Please refresh shortly.');
      }

      setUser(data.user);
      setRepos(data.repos);
      setCalendar(data.calendar);
      setLastUpdated(new Date());
      setError(null);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Unable to refresh GitHub data right now.');
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    document.title = 'GitHub | Pratik Poudel';
    void refreshGithubData(true);

    const interval = window.setInterval(() => {
      void refreshGithubData();
    }, REFRESH_INTERVAL);

    const refreshWhenVisible = () => {
      if (document.visibilityState === 'visible') {
        void refreshGithubData();
      }
    };

    document.addEventListener('visibilitychange', refreshWhenVisible);

    return () => {
      window.clearInterval(interval);
      document.removeEventListener('visibilitychange', refreshWhenVisible);
    };
  }, [refreshGithubData]);

  return (
    <div className={styles.page}>
      <div className={styles.container}>
        {/* Header */}
        <header className={styles.header}>
          <div className={styles.profile}>
            {user ? (
              <Image
                src={user.avatar_url}
                className={styles.avatar}
                alt={user.login}
                width={80}
                height={80}
                priority
                unoptimized
              />
            ) : (
              <div className={styles.avatar} aria-label="Loading GitHub avatar" />
            )}
            <div className={styles.profileInfo}>
              <h1 className={styles.name}>{user?.login ?? GITHUB_USERNAME}</h1>
              <span className={styles.handle}>@{user?.login ?? GITHUB_USERNAME}</span>
            </div>
          </div>

          <a
            href={`https://github.com/${GITHUB_USERNAME}`}
            target="_blank"
            rel="noopener noreferrer"
            className={styles.profileLink}
          >
            <VscGithub size={18} />
            <span>View Profile</span>
            <VscLinkExternal size={14} />
          </a>
        </header>

        {error && (
          <div role="status" aria-live="polite" className={styles.section}>
            <p>{error}</p>
            <button
              type="button"
              onClick={() => void refreshGithubData(true)}
              style={{
                marginTop: 8,
                padding: '8px 12px',
                borderRadius: 6,
                border: '1px solid var(--explorer-border)',
                background: 'transparent',
                color: 'var(--text-color)',
                cursor: 'pointer',
              }}
            >
              Try again
            </button>
          </div>
        )}

        {/* Stats */}
        <div className={styles.statsGrid} aria-busy={loading}>
          <div className={styles.statCard}>
            <div className={styles.statIcon}><VscRepo size={20} /></div>
            <div className={styles.statInfo}>
              <span className={styles.statValue}>{user?.public_repos ?? '—'}</span>
              <span className={styles.statLabel}>Repositories</span>
            </div>
          </div>

          <div className={styles.statCard}>
            <div className={styles.statIcon}><VscPerson size={20} /></div>
            <div className={styles.statInfo}>
              <span className={styles.statValue}>{user?.followers ?? '—'}</span>
              <span className={styles.statLabel}>Followers</span>
            </div>
          </div>

          <div className={styles.statCard}>
            <div className={styles.statIcon}><VscStarEmpty size={20} /></div>
            <div className={styles.statInfo}>
              <span className={styles.statValue}>
                {user ? repos.reduce((acc, repo) => acc + repo.stargazers_count, 0) : '—'}
              </span>
              <span className={styles.statLabel}>Featured Repo Stars</span>
            </div>
          </div>

          <div className={styles.statCard}>
            <div className={styles.statIcon}><VscRepoForked size={20} /></div>
            <div className={styles.statInfo}>
              <span className={styles.statValue}>
                {user ? repos.reduce((acc, repo) => acc + repo.forks, 0) : '—'}
              </span>
              <span className={styles.statLabel}>Featured Repo Forks</span>
            </div>
          </div>
        </div>

        {/* Contribution Graph */}
        <section className={styles.section}>
          <h2 className={styles.sectionTitle}>Contribution Activity</h2>
          <div className={styles.contributions} aria-label={calendar ? `${calendar.totalContributions} contributions in the last year` : 'Loading contribution activity'}>
            {calendar ? (
              <>
                <div className={styles.contributionSummary}>{calendar.totalContributions.toLocaleString()} contributions in the last year</div>
                <div className={styles.calendarScroll}>
                  <div className={styles.calendarGrid} role="grid" aria-label="Contribution activity by day">
                    {calendar.weeks.map((week, weekIndex) => (
                      <div className={styles.calendarWeek} role="row" key={weekIndex}>
                        {week.contributionDays.map((day) => (
                          <span
                            key={day.date}
                            role="gridcell"
                            className={styles.calendarDay}
                            data-level={day.contributionLevel === 'FOURTH_QUARTILE' ? 4 : day.contributionLevel === 'THIRD_QUARTILE' ? 3 : day.contributionLevel === 'SECOND_QUARTILE' ? 2 : day.contributionLevel === 'FIRST_QUARTILE' ? 1 : 0}
                            title={`${day.contributionCount} contributions on ${day.date}`}
                            aria-label={`${day.contributionCount} contributions on ${day.date}`}
                          />
                        ))}
                      </div>
                    ))}
                  </div>
                </div>
                <div className={styles.calendarLegend}><span>Less</span>{[0,1,2,3,4].map(level=><span key={level} className={styles.calendarDay} data-level={level} />)}<span>More</span></div>
              </>
            ) : loading ? <p>Loading contribution activity…</p> : <p>Contribution activity is temporarily unavailable.</p>}
          </div>
        </section>

        {/* Repositories */}
        <section className={styles.section}>
          <div className={styles.sectionHeader}>
            <h2 className={styles.sectionTitle}>Popular Repositories</h2>
            <a
              href={`https://github.com/${GITHUB_USERNAME}?tab=repositories`}
              target="_blank"
              rel="noopener noreferrer"
              className={styles.viewAll}
            >
              View All
              <VscLinkExternal size={14} />
            </a>
          </div>

          <div className={styles.reposGrid} aria-busy={loading}>
            {repos.map((repo) => <RepoCard key={repo.id} repo={repo} />)}
            {!repos.length && loading && <p>Loading your GitHub repositories…</p>}
            {!repos.length && !loading && !error && <p>No repositories to display yet.</p>}
          </div>
        </section>
      </div>
    </div>
  );
}
